import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import {
  ARTIFACT_CAPABILITY_MANIFEST_SCHEMA,
  validateArtifactCapabilityDeclaration,
  validateArtifactCapabilityManifest,
  validateArtifactCapabilityFixture,
} from "../../../packages/artifact-invocation/src/index.mjs";
import { canonicalJson } from "../../../packages/url-module/src/index.mjs";

const here = path.dirname(fileURLToPath(import.meta.url));
const appRoot = path.resolve(here, "..");
const repoRoot = path.resolve(appRoot, "../..");
const parseArgs = input => {
  const result = { capabilitiesRoot: path.join(appRoot, "capabilities"), check: false, output: path.join(appRoot, "generated", "capability-registry.mjs") };
  for (let index = 0; index < input.length; index += 1) {
    const value = input[index];
    if (value === "--check") result.check = true;
    else if (value === "--capabilities-root") result.capabilitiesRoot = path.resolve(input[++index]);
    else if (value === "--output") result.output = path.resolve(input[++index]);
    else throw new Error(`build-registry: unsupported argument ${value}`);
  }
  return result;
};

const posixRelative = (from, to) => {
  const relative = path.relative(from, to).split(path.sep).join("/");
  return relative.startsWith(".") ? relative : `./${relative}`;
};

const noModuleDependencies = source => {
  if (/\bimport\s*(?:\(|["'{*])/u.test(source)) return false;
  if (/\bexport\s+[^;\n]*\sfrom\s*["']/u.test(source)) return false;
  return true;
};

const runtimeSourceRoots = Object.freeze([
  path.join(repoRoot, "packages", "artifact-invocation", "src"),
  path.join(repoRoot, "packages", "artifact-invocation", "package.json"),
  path.join(repoRoot, "packages", "url-module", "src"),
  path.join(repoRoot, "packages", "url-module", "package.json"),
  path.join(repoRoot, "packages", "artifact-reference", "src"),
  path.join(repoRoot, "packages", "artifact-reference", "package.json"),
  path.join(repoRoot, "packages", "a2ui-browser", "src"),
  path.join(repoRoot, "packages", "a2ui-browser", "package.json"),
  path.join(repoRoot, "packages", "core-port", "src", "jsonl.mjs"),
  path.join(repoRoot, "packages", "core-port", "src", "project.mjs"),
  path.join(repoRoot, "packages", "core-port", "src", "catalog.mjs"),
  path.join(repoRoot, "packages", "core-port", "src", "registry.mjs"),
  path.join(appRoot, "src", "invocation-action.mjs"),
  path.join(appRoot, "src", "pinned-view.mjs"),
  path.join(appRoot, "src", "services.mjs"),
  path.join(appRoot, "src", "shell-core.mjs"),
]);

const collectFiles = async target => {
  const stat = await fs.stat(target);
  if (stat.isFile()) return [target];
  const result = [];
  for (const entry of (await fs.readdir(target, { withFileTypes: true })).sort((left, right) => left.name.localeCompare(right.name))) {
    const child = path.join(target, entry.name);
    if (entry.isDirectory()) result.push(...await collectFiles(child));
    else if (entry.isFile()) result.push(child);
  }
  return result;
};

const createRuntimeBuild = async () => {
  const files = [...new Set((await Promise.all(runtimeSourceRoots.map(collectFiles))).flat())].sort();
  const descriptors = [];
  for (const file of files) {
    const bytes = await fs.readFile(file);
    descriptors.push(Object.freeze({
      bytes: bytes.byteLength,
      path: path.relative(repoRoot, file).split(path.sep).join("/"),
      sha256: `sha256:${createHash("sha256").update(bytes).digest("hex")}`,
    }));
  }
  const body = Object.freeze({ files: Object.freeze(descriptors), id: "artifact-shell", schema: "artifact-runtime-build/1", version: "1" });
  return Object.freeze({ ...body, digest: `sha256:${createHash("sha256").update(canonicalJson(body)).digest("hex")}` });
};

const createSource = (manifests, runtimeBuild) => {
  const serialized = canonicalJson(manifests);
  const serializedBuild = canonicalJson(runtimeBuild);
  return `// Generated by apps/artifact-shell/scripts/build-registry.mjs. Do not edit.\n`
    + `const deepFreeze=value=>{if(value&&typeof value==="object"&&!Object.isFrozen(value)){for(const child of Object.values(value))deepFreeze(child);Object.freeze(value);}return value;};\n`
    + `export const ARTIFACT_CAPABILITY_REGISTRY_BASE_URL=import.meta.url;\n`
    + `export const ARTIFACT_SHELL_BUILD=deepFreeze(${serializedBuild});\n`
    + `export const TRUSTED_ARTIFACT_CAPABILITIES=deepFreeze(${serialized});\n`;
};

export const buildRegistry = async options => {
  const entries = (await fs.readdir(options.capabilitiesRoot, { withFileTypes: true }))
    .filter(entry => entry.isDirectory())
    .map(entry => entry.name)
    .sort();
  if (entries.length === 0) throw new Error("build-registry: no capability directories found");
  const manifests = [];
  const outputDir = path.dirname(options.output);
  for (const directory of entries) {
    const root = path.join(options.capabilitiesRoot, directory);
    const declaration = validateArtifactCapabilityDeclaration(JSON.parse(await fs.readFile(path.join(root, "manifest.json"), "utf8")));
    const fixturePaths = [...declaration.fixtures.pass.map(file => ["pass", file]), ...declaration.fixtures.destructive.map(file => ["destructive", file])];
    for (const [kind, file] of fixturePaths) {
      const fixturePath = path.resolve(root, file);
      if (!(fixturePath === root || fixturePath.startsWith(`${root}${path.sep}`))) throw new Error(`build-registry: fixture escapes capability root: ${file}`);
      const fixture = validateArtifactCapabilityFixture(JSON.parse(await fs.readFile(fixturePath, "utf8")));
      if (fixture.kind !== kind) throw new Error(`build-registry: ${file} kind mismatch: ${fixture.kind} != ${kind}`);
      if (!fixture.runtimes.every(runtime => declaration.requires.runtimes.includes(runtime))) throw new Error(`build-registry: ${file} declares unsupported runtime`);
    }
    const enginePath = path.join(root, declaration.engine.file);
    const engineBytes = await fs.readFile(enginePath);
    if (engineBytes.byteLength > declaration.limits.maxEngineBytes) throw new Error(`build-registry: ${declaration.id} engine exceeds maxEngineBytes`);
    const source = engineBytes.toString("utf8");
    if (!noModuleDependencies(source)) throw new Error(`build-registry: ${declaration.id} engine must be a self-contained ESM file`);
    const manifest = validateArtifactCapabilityManifest({
      ...declaration,
      engine: {
        bytes: engineBytes.byteLength,
        digest: `sha256:${createHash("sha256").update(engineBytes).digest("hex")}`,
        href: posixRelative(outputDir, enginePath),
        kind: declaration.engine.kind,
      },
      schema: ARTIFACT_CAPABILITY_MANIFEST_SCHEMA,
    });
    manifests.push(manifest);
  }
  const runtimeBuild = await createRuntimeBuild();
  const source = createSource(manifests, runtimeBuild);
  if (options.check) {
    let current = null;
    try { current = await fs.readFile(options.output, "utf8"); } catch (_) {}
    if (current !== source) throw new Error(`build-registry: generated registry is stale: ${options.output}`);
    return Object.freeze({ changed: false, manifests, output: options.output, runtimeBuild, source });
  }
  await fs.mkdir(outputDir, { recursive: true });
  await fs.writeFile(options.output, source);
  return Object.freeze({ changed: true, manifests, output: options.output, runtimeBuild, source });
};

if (pathToFileURL(process.argv[1] ?? "").href === import.meta.url) {
  const options = parseArgs(process.argv.slice(2));
  const result = await buildRegistry(options);
  console.log(JSON.stringify(options.check ? {
    schema: "check-receipt/1",
    checkId: "ui.artifact-shell.registry",
    ownerRepo: "ui",
    lane: "repo",
    kind: "normal",
    status: "PASS",
    assertions: result.manifests.length + result.runtimeBuild.files.length + 2,
  } : {
    schema: "artifact-capability-registry-build/1",
    status: "PASS",
    capabilities: result.manifests.length,
    output: result.output,
  }));
}
